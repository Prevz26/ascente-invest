class SuccessCallback(BaseModel):
    """Schema for successful payment callback from CryptAPI"""
    uuid: str = Field(
        description="Unique identifier for tracking payment callbacks"
    )
    address_in: str = Field(
        description="Address generated by CryptAPI where customer sent the payment"
    )
    address_out: str = Field(
        description="Address(es) where CryptAPI forwarded the payment"
    )
    txid_in: str = Field(
        description="Transaction hash of customer's payment"
    )
    txid_out: str = Field(
        description="Transaction hash of the forwarded payment"
    )
    confirmations: int = Field(
        description="Number of blockchain confirmations"
    )
    value_coin: float = Field(
        description="Payment amount before fees"
    )
    value_coin_convert: Optional[dict] = Field(
        default=None,
        description="JSON-encoded FIAT currency conversions of value_coin"
    )
    value_forwarded_coin: float = Field(
        description="Payment amount after fees"
    )
    value_forwarded_coin_convert: Optional[dict] = Field(
        default=None,
        description="JSON-encoded FIAT currency conversions of value_forwarded_coin"
    )
    fee_coin: float = Field(
        description="Fee paid to CryptAPI"
    )
    coin: str = Field(
        description="Ticker of the coin used for payment (btc, bch, ltc, eth, trx, etc)"
    )
    price: float = Field(
        description="Coin price in USD at callback time"
    )
    pending: int = Field(
        default=0,
        description="0 for confirmed payments"
    )

